
-- MEMBER
ALTER TABLE member
ADD CONSTRAINT CHK_MEMBER_PHONE
CHECK (phone REGEXP '^[0-9]+$');

ALTER TABLE member
ADD CONSTRAINT CHK_MEMBER_ROLE
CHECK (role IN ('USER', 'ADMIN'));

-- PAYMENT
ALTER TABLE payment
ADD CONSTRAINT CHK_PAYMENT_STATUS
CHECK (status IN ('PAID', 'CANCELED', 'REFUNDED'));

-- SEAT
ALTER TABLE seat
ADD CONSTRAINT CHK_SEAT_SECTION
CHECK (section IN ('F1', 'F2', 'F3', 'F4', 'S1', 'S2', 'G'));

ALTER TABLE seat
ADD CONSTRAINT CHK_SEAT_RANK
CHECK (seat_rank IN ('FS', 'VIP', 'R'));

ALTER TABLE seat
ADD CONSTRAINT CHK_SEAT_STATUS
CHECK (status IN ('AVAILABLE', 'HELD', 'RESERVED'));

-- RESERVATION
ALTER TABLE reservation
ADD CONSTRAINT CHK_RESERVATION_STATUS
CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELED'));

-- PERFORMANCE
ALTER TABLE performance
ADD CONSTRAINT CHK_PERFORMANCE_GENRE
CHECK (genre IN ('K_POP', 'HIPHOP_RANDB','VALLAD','ETC'));

ALTER TABLE performance
ADD CONSTRAINT CHK_PERFORMANCE_STATUS
CHECK (status IN ('UPCOMING', 'ON_SALE', 'SOLD_OUT', 'CLOSED', 'CANCELED'));

-- PRICE
